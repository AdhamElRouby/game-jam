// Visual tour: solo dev room, warp to each checkpoint, show each shape. npx tsx tests/tour.ts [base] [w] [h]
import { chromium } from 'playwright';

const base = process.argv[2] ?? 'http://localhost:5173';
const W = Number(process.argv[3] ?? 1280);
const H = Number(process.argv[4] ?? 720);
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=metal', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: W, height: H } });
const logs: string[] = [];
page.on('console', (m) => (m.type() === 'error' || m.type() === 'warning') && logs.push(`[${m.type()}] ${m.text()}`));
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.goto(base + '/?dev');
await page.waitForTimeout(2500);
await page.screenshot({ path: `tests/out/tour-landing-${W}.png` });
await page.getByText('Solo test room (dev)').click();
await page.waitForTimeout(6500);
const dev = (cmd: string) => page.evaluate(`window.__SH_NET.dev(${cmd})`);
const shot = async (name: string, wait = 1200) => {
  await page.waitForTimeout(wait);
  await page.screenshot({ path: `tests/out/tour-${name}.png` });
};
await page.evaluate(`document.querySelector('.controls')?.click()`);
await dev(`{ me: [0, 0, 5] }`);
await shot('ch1');
await dev(`{ warp: 1 }`);
await dev(`{ art: [0, 1.1, -20.5], me: [1.5, 0, -18] }`);
await shot('ch1-arch', 800);
await dev(`{ shape: 1 }`);
await shot('ch1-long', 900);
await dev(`{ warp: 1 }`);
await dev(`{ art: [-2.5, 1.1, -56], me: [0, 0, -54] }`);
await shot('ch2', 1500);
await dev(`{ shape: 1 }`);
await shot('ch2-long', 2600);
await dev(`{ warp: 2 }`);
await dev(`{ art: [-4.5, 1.1, -100], me: [-2.5, 0, -98.5] }`);
await shot('ch3', 1500);
await dev(`{ shape: 2 }`);
await shot('ch3-tall', 900);
await dev(`{ warp: 3 }`);
await shot('ch4', 1500);
await dev(`{ art: [5, 9.2, -113], me: [5, 8, -110.5] }`);
await page.waitForTimeout(500);
await dev(`{ shape: 3 }`);
await shot('ch4-round', 900);
await dev(`{ art: [0, 1.2, -160], me: [1.5, 0, -158] }`);
await shot('goal', 1200);
await dev(`{ finish: true }`);
await shot('ending-2s', 2000);
await shot('ending-6s', 4000);
await shot('results', 3000);
console.log(logs.filter((l) => !l.includes('Clock') && !l.includes('PCFSoft')).slice(0, 20).join('\n'));
await browser.close();
